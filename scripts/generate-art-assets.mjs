import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = resolve(root, 'dist');
const artwork = JSON.parse(await readFile(resolve(dist, 'art/manifest.json'), 'utf8'));
const critical = new Set();
const files = new Set();
const add = (path, first = false) => {
  const normalized = './' + path.replace(/^\.\//, '');
  if (!/^\.\/(art|settlement)\/[\w./-]+$/.test(normalized) || normalized.includes('/../')) throw new Error(`Invalid art path: ${path}`);
  files.add(normalized);
  if (first) critical.add(normalized);
};
const tiles = [...['Man', 'Pin', 'Sou'].flatMap(suit => Array.from({ length: 9 }, (_, i) => suit + (i + 1))), 'Ton', 'Nan', 'Shaa', 'Pei', 'Haku', 'Hatsu', 'Chun'];
for (const name of tiles) add(`art/tiles/${name}.svg`, true);
for (const path of Object.values(artwork.relics)) add(path);
for (const path of Object.values(artwork.backgrounds)) add(path);
for (const name of ['rank_brush']) {
  if (!artwork.relics[name]) throw new Error(`Missing initial relic art: ${name}`);
  add(artwork.relics[name], true);
}
for (const name of ['page', 'board']) add(artwork.backgrounds[name], true);

// Only the active V4 renderer's themes are included. Old V3 videos, exported
// preview GIFs and unused illustrations do not consume a player's bandwidth.
const library = await readFile(resolve(dist, 'settlement/v4/library-player.js'), 'utf8');
const themes = [...library.matchAll(/^\s{2}(\w+):\{background:'([^']+)'/gm)];
if (!themes.length) throw new Error('No V4 presentation themes found');
for (const [, theme, background] of themes) {
  add('settlement/' + new URL(background, 'https://art.invalid/settlement/v4/').pathname.split('/settlement/')[1]);
  for (const pose of ['charge', 'dash', 'release']) add(`settlement/v4/assets/${theme}-${pose}.webp`);
}
add('settlement/cinematic/MaShanZheng-subset.woff2');
for (const path of ['pixi/pixi.min.js', 'pixi/pixi-filters.js', 'effekseer/effekseer.min.js', 'effekseer/effekseer.wasm']) add(`settlement/v4/vendor/${path}`);
async function addEffects(directory) {
  for (const entry of await readdir(resolve(dist, directory), { withFileTypes: true })) {
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) await addEffects(path);
    else if (/\.(?:efkefc|png)$/.test(path)) add(path);
  }
}
await addEffects('settlement/v4/fx');
const entries = [];
for (const path of [...files].sort()) {
  const bytes = await readFile(resolve(dist, path));
  entries.push({ path, sha256: createHash('sha256').update(bytes).digest('hex'), bytes: bytes.length, critical: critical.has(path) });
}
const version = createHash('sha256').update(JSON.stringify({ entries, artwork })).digest('hex').slice(0, 20);
const manifest = { schema: 1, version, entries, artwork };
const serialized = JSON.stringify(manifest);
await writeFile(resolve(dist, 'art-assets.js'), `// Generated by scripts/generate-art-assets.mjs; do not edit.\nexport const ART_ASSETS = ${serialized};\n`);
await writeFile(resolve(dist, 'art-assets-sw.js'), `// Generated by scripts/generate-art-assets.mjs; do not edit.\nself.JADE_ART_ASSETS = ${serialized};\n`);
const total = entries.reduce((sum, asset) => sum + asset.bytes, 0);
const first = entries.filter(asset => asset.critical).reduce((sum, asset) => sum + asset.bytes, 0);
console.log(`Art ${version}: ${entries.length} files / ${total} bytes; initial ${critical.size} files / ${first} bytes.`);
